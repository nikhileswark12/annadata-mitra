# TEST CASE 2 — Invalid Request
def test_invalid_request(client):
    # missing location
    res1 = client.post('/weather-risk', json={"crop": "Wheat"})
    assert res1.status_code == 422
    assert res1.get_json()["success"] is False
    assert "Missing field: location" in res1.get_json()["error"]

    # empty JSON
    res2 = client.post('/weather-risk', json={})
    assert res2.status_code == 422
    assert res2.get_json()["success"] is False

    # missing JSON body triggers 415 in Flask
    res3 = client.post('/weather-risk')
    assert res3.status_code == 415

