# TEST CASE 4 — Weather Reasoning
def test_weather_reasoning():
    # Verify risk evaluation executes, severity ordering works
    weather = {
        "temperature": 45,
        "humidity": 90,
        "rainfall": 100,
        "windSpeed": 60
    }
    risk_rules = [
        {
            "id": "W1",
            "type": "Heat Stress",
            "condition": "lambda w: w['temperature'] > 40",
            "message": "lambda w: f'Temp {w[\"temperature\"]}'",
            "recommendation": "Cool down",
            "severity": "High"
        },
        {
            "id": "W2",
            "type": "Cold Stress",
            "condition": "lambda w: w['temperature'] < 10",
            "message": "lambda w: 'Cold'",
            "recommendation": "Heat up",
            "severity": "Medium"
        }
    ]
    no_risk_msg = {"type": "No Risk", "severity": "Low", "message": "All good"}
    
    res = WeatherReasoner.reason(weather, risk_rules, no_risk_msg)
    decisions = res["decision"]
    assert len(decisions) == 1
    assert decisions[0]["type"] == "Heat Stress"

    # Default no-risk message
    good_weather = {"temperature": 25}
    res_good = WeatherReasoner.reason(good_weather, risk_rules, no_risk_msg)
    assert len(res_good["decision"]) == 1
    assert res_good["decision"][0]["type"] == "No Risk"

